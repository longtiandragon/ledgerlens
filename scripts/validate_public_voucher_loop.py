"""Reproducible API workflow using public MOF examples and labelled training faults.

Runs the real FastAPI app in an isolated child-process SQLite environment. There
are no model calls, human signoffs, real-company records, or tax conclusions.
Literal expected results below are handwritten validation data, never sent to a
runtime Agent. Original XML, derived projections and synthetic faults stay apart.
"""
from __future__ import annotations

import argparse
from copy import deepcopy
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from datasets.mof_vouchers import NS, SAMPLES, verify_package  # noqa: E402

VERSION = 'public-voucher-loop-v1'
# Independent hand-read amounts from the public XML; NOT generated by app rules.
EXPECTED = {
    'einv_spcl_20231231_22442000000921291350.xml':
        [('原材料', '9000.00', '0.00'), ('应交税费/应交增值税-进项税额', '1170.00', '0.00'), ('银行存款', '0.00', '10170.00')],
    'einv_ord_20220326_22442000000005170034.xml':
        [('管理费用', '500.00', '0.00'), ('银行存款', '0.00', '500.00')],
}
ACCOUNT_MAP = {'原材料': '1403', '应交税费/应交增值税-进项税额': '2221.01', '银行存款': '1002', '管理费用': '6602'}


def encode(value):
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode()


def digest(data):
    return hashlib.sha256(data).hexdigest()


def worker(bundle: Path, output: Path):
    import ipaddress
    import xml.etree.ElementTree as ET
    sys.path.insert(0, str(ROOT / 'backend'))
    attempts = []

    def guard(event, args):
        if event == 'socket.connect':
            address = args[1]
            if isinstance(address, tuple) and ipaddress.ip_address(address[0]).is_loopback:
                return
            attempts.append('external_network')
            raise RuntimeError('External network is disabled during validation')

    sys.addaudithook(guard)
    from app.config import settings
    from app import model_gateway

    def forbidden(*args, **kwargs):
        attempts.append('model_constructor')
        raise RuntimeError('Model calls are disabled in this offline validator')

    model_gateway.DeepSeekGateway = forbidden
    from fastapi.testclient import TestClient
    from app.main import app

    report = {'schema_version': VERSION, 'status': 'running', 'started_at': datetime.now(timezone.utc).isoformat(),
              'data_nature': 'public_standard_examples_plus_explicit_synthetic_faults',
              'professional_review': 'AI review only; not independent professional signoff',
              'model_requests': 0, 'checks': [], 'sources': [], 'artifacts': [],
              'limitations': ['Two official illustrative files, not enterprise invoices or a full ledger.',
                  'PostingDate is a declared teaching convention, not transaction occurrence evidence.',
                  'Original accounting entries do not prove recognition, payment, VAT eligibility or tax compliance.',
                  'The duplicate and invoice observation are synthetic training inputs; no real fraud or refund is claimed.',
                  'In-process real API application, not a browser or network-service deployment test.']}

    def save():
        (output / 'report.json').write_bytes(encode(report))

    def check(name, condition):
        report['checks'].append({'name': name, 'passed': bool(condition)})
        save()
        if not condition:
            raise ValueError(name)

    def artifact(name, content):
        raw = content if isinstance(content, bytes) else encode(content)
        (output / name).write_bytes(raw)
        report['artifacts'].append({'file': name, 'sha256': digest(raw)})

    try:
        check('Isolated local mode without provider key', settings.data_dir.resolve() == (output / 'runtime').resolve()
              and not settings.deepseek_api_key and settings.task_mode == 'local' and settings.auth_mode == 'single_user')
        with TestClient(app) as client:
            def request(method, path, expected=200, **kwargs):
                response = client.request(method, '/api/v1' + path, **kwargs)
                if response.status_code != expected:
                    raise ValueError(f'{method} {path}: {response.status_code} {response.text[:600]}')
                return response

            def book(name, period, accounts):
                return request('POST', '/books', expected=201, json={
                    'name': name, 'period': period, 'framework': 'CAS', 'accounts': accounts}).json()['id']

            def upload(identity, name, package):
                raw = encode(package)
                preview = request('POST', '/imports', data={'book_id': identity, 'synthetic': 'true'},
                                  files={'file': (name, raw, 'application/json')}).json()
                check(name + ': no quarantined rows', not preview['errors'])
                downloaded = request('GET', f'/documents/{preview["document_id"]}/file').content
                check(name + ': uploaded source unchanged', downloaded == raw)
                confirmed = request('POST', f'/imports/{preview["id"]}/confirm').json()
                return preview, confirmed

            packages = {}
            for filename in SAMPLES:
                package = json.loads((bundle / (filename + '.json')).read_text(encoding='utf-8'))
                verify_package(package)
                packages[filename] = package
                raw = (bundle / filename).read_bytes()
                check(filename + ': embedded XML equals downloaded bytes', package['source']['original_xml_utf8'].encode() == raw)
                rows = package['records']
                check(filename + ': handwritten source line comparison',
                      [(r['account'], r['debit'], r['credit']) for r in rows] == EXPECTED[filename])
                original = ET.fromstring(raw)
                for row, locator in zip(rows, package['field_provenance'], strict=True):
                    node = original.find(locator['xml_path'], NS)
                    check(row['source_id'] + ': XML pointer resolves', node is not None and
                          node.find('einv:NameOfGeneralLedgerSubject', NS).text == row['account'].split('/')[0])
                identity = book('公开标准样例（非企业账套）' + filename[:9], rows[0]['period'], sorted({r['account'] for r in rows}))
                preview, confirmed = upload(identity, 'synthetic-source-' + filename + '.json', package)
                checks = request('POST', '/check-runs', json={'book_id': identity, 'snapshot_id': confirmed['snapshot_id']}).json()
                check(filename + ': baseline has no voucher imbalance',
                      not any(c['rule_id'] == 'VOUCHER_BALANCE' for c in checks['cases']))
                check(filename + ': every source journal imported', confirmed['imported'] == len(EXPECTED[filename]))
                _, repeated = upload(identity, 'synthetic-repeat-' + filename + '.json', package)
                check(filename + ': repeat creates no duplicate records', repeated['imported'] == 0 and repeated['duplicate_count'] == len(rows))
                overview = request('GET', f'/books/{identity}/overview').json()
                check(filename + ': missing bank evidence remains unavailable',
                      next(x for x in overview['capabilities'] if x['name'] == '银行往来核对')['available'] is False)
                report['sources'].append({'filename': filename, 'sha256': digest(raw), 'record_count': len(rows),
                                          'book_id': identity, 'snapshot_id': confirmed['snapshot_id'],
                                          'warnings': package['warnings']})

            # Independent scenario: a full duplicate plus a synthetic invoice
            # observation. Accounting codes are an explicit teaching mapping,
            # not extracted from XML; 2221.01 is a local detail code.
            source = packages[next(iter(SAMPLES))]
            rows = deepcopy(source['records'])
            for row in rows:
                row['account'] = ACCOUNT_MAP[row['account']]
                row['source_id'] = 'training-mapped:' + row['source_id']
                row['description'] = '教学映射分录；非原XML科目代码。' + row['description']
            base_rows = deepcopy(rows)
            duplicates = deepcopy(rows)
            for index, row in enumerate(duplicates):
                row['voucher_id'] = 'TRAINING-DUPLICATE'
                row['source_id'] = f'training-duplicate:{index}'
                row['description'] = '人为注入的完整重复记账教学故障；不是官方原始分录。'
            invoice = {'source_id': 'training-invoice-observation', 'kind': 'invoice', 'business_date': '2023-12-31',
                       'period': '2023-12', 'currency': 'CNY', 'invoice_id': rows[0]['invoice_id'],
                       'counterparty': rows[0]['counterparty'], 'amount': '10170.00',
                       'description': '教学构造的发票观察，金额摘自示例价税合计，日期人为沿用过账日；非真实发票/开票日。'}
            package = {'data_nature': 'synthetic_duplicate_training_scenario', 'source_package': source,
                       'account_mapping': ACCOUNT_MAP, 'mapping_note': '2221.01为自定义明细科目；日期仅教学约定。',
                       'records': [*rows, *duplicates, invoice]}
            artifact('training-input.json', package)
            identity = book('公开样例派生重复记账教学故障（非企业账套）', '2023-12', list(ACCOUNT_MAP.values()))
            _, confirmed = upload(identity, 'synthetic-duplicate-training.json', package)
            snap = confirmed['snapshot_id']
            cases = request('POST', '/check-runs', json={'book_id': identity, 'snapshot_id': snap}).json()['cases']
            targets = [c for c in cases if c['rule_id'] == 'DUPLICATE_INVOICE']
            check('Exactly one duplicate-invoice training finding', len(targets) == 1)
            case = targets[0]
            check('Independent 10170.00 excess', case['metrics']['excess'] == '10170.00')
            run = request('POST', f'/cases/{case["id"]}/investigate', json={'mode': 'rules'}).json()
            run = request('GET', f'/runs/{run["id"]}').json()
            check('Rules investigation completes without model requests', run['status'] == 'complete' and run['usage'].get('calls', 0) == 0)
            before = request('GET', f'/books/{identity}/records').json()
            evidence = request('GET', f'/cases/{case["id"]}/evidence').json()
            check('All training evidence is labelled synthetic', bool(evidence) and all(e['synthetic'] for e in evidence))
            snapshot = request('GET', f'/snapshots/{snap}').json()
            check('All evidence is in the frozen snapshot', all(e['record']['id'] in snapshot['record_ids'] for e in evidence))
            # Manual reversal: restore duplicate book effects, not an actual refund.
            adjustment = [dict(voucher_id='SIM-REVERSAL', account=account, debit=debit, credit=credit,
                               invoice_id=invoice['invoice_id'], counterparty=invoice['counterparty'],
                               business_date='2023-12-31', period='2023-12') for account, debit, credit in
                          [('1403', '0.00', '9000.00'), ('2221.01', '0.00', '1170.00'), ('1002', '10170.00', '0.00')]]
            sim = request('POST', '/simulations', json={'case_id': case['id'], 'adjustments': adjustment}).json()
            check('Balanced reversal including tax component', sim['balanced'] and not sim['violations'])
            check('Independent original net balances restored in simulation only',
                  sim['after'] == {'1403': '9000.00', '2221.01': '1170.00', '1002': '-10170.00'})
            check('Target duplicate finding disappears in simulated branch',
                  not any(f['rule_id'] == 'DUPLICATE_INVOICE' for f in sim['new_findings']))
            # A missing tax leg must NOT appear to be a successful correction.
            bad_sim = request('POST', '/simulations', json={'case_id': case['id'], 'adjustments': [adjustment[0], adjustment[2]]}).json()
            check('Incomplete reversal rejected as unbalanced', not bad_sim['balanced'] and bool(bad_sim['violations']))
            review = {'case_id': case['id'], 'expected_snapshot_id': snap, 'decision': 'reserved',
                      'comment': '自动化教学流程记录，非人工专业签字。仅模拟撤销重复账面影响，不证明退款、付款或进项税抵扣资格；失败草稿保留。'}
            request('POST', '/reviews', json=review)
            exported = request('GET', f'/exports/cases/{case["id"]}?format=json').json()
            artifact('workpaper.json', exported)
            artifact('workpaper.md', request('GET', f'/exports/cases/{case["id"]}?format=markdown').content)
            check('Workpaper includes run, evidence, both successful and failed drafts',
                  any(r['id'] == run['id'] for r in exported['runs']) and len(exported['simulations']) == 2 and
                  {e['id'] for e in exported['evidence']} == {e['id'] for e in evidence})
            check('Original ledger remains unchanged after simulations and review', request('GET', f'/books/{identity}/records').json() == before)
            late = deepcopy(base_rows)
            for index, row in enumerate(late):
                row['source_id'] = f'training-late:{index}'
                row['voucher_id'] = 'TRAINING-LATE'
                row['invoice_id'] = ''
                row['description'] = '独立迟到资料教学注入；不表示实际新增采购。'
            upload(identity, 'synthetic-late-training.json', {'records': late, 'data_nature': 'synthetic_late_material'})
            response = client.post('/api/v1/reviews', json=review)
            check('Late data invalidates old review', response.status_code == 409)
            check('Historical evidence unchanged after late data', request('GET', f'/cases/{case["id"]}/evidence').json() == evidence)
            historical = request('GET', f'/exports/cases/{case["id"]}?format=json').json()
            check('Historical workpaper retained and marked stale', historical['stale'] is True)
            artifact('historical-workpaper.json', historical)
            report['scenario'] = {'book_id': identity, 'snapshot_id': snap, 'case_id': case['id'], 'run_id': run['id'],
                                  'source_line_count': 3, 'duplicate_line_count': 3, 'synthetic_invoice_count': 1,
                                  'source_lines_sha256': digest(encode(base_rows)),
                                  'fault_lines_sha256': digest(encode(duplicates)), 'training_package_sha256': digest(encode(package))}
        check('No external network or model construction attempted', not attempts)
        report['status'] = 'passed'
    except Exception as exc:
        report['status'], report['error'] = 'failed', repr(exc)
        raise
    finally:
        report['finished_at'] = datetime.now(timezone.utc).isoformat()
        report['network_or_model_attempts'] = attempts
        save()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bundle', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--worker', action='store_true', help=argparse.SUPPRESS)
    args = parser.parse_args()
    if args.worker:
        worker(args.bundle.resolve(), args.output.resolve())
        return 0
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    from scripts.validate_clean_checkout import isolated_environment
    env = isolated_environment() | {'DATA_DIR': str(output / 'runtime'),
        'DATABASE_URL': 'sqlite:///' + (output / 'runtime' / 'ledgerlens.sqlite').as_posix(),
        'DEEPSEEK_API_KEY': '', 'TASK_MODE': 'local', 'AUTH_MODE': 'single_user', 'TELEMETRY_ENABLED': 'false'}
    with (output / 'execution.log').open('w', encoding='utf-8') as log:
        result = subprocess.run([sys.executable, str(Path(__file__).resolve()), '--worker',
                                 '--bundle', str(args.bundle.resolve()), '--output', str(output)],
                                cwd=output, env=env, stdout=log, stderr=subprocess.STDOUT,
                                creationflags=subprocess.CREATE_NO_WINDOW if os.name == 'nt' else 0)
    if not (output / 'report.json').exists():
        (output / 'report.json').write_bytes(encode({'schema_version': VERSION, 'status': 'failed',
                                                   'error': 'Worker ended before producing a report', 'exit_code': result.returncode}))
    print((output / 'report.json').read_text(encoding='utf-8'))
    return result.returncode


if __name__ == '__main__':
    raise SystemExit(main())
