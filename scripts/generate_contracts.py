"""Export the API description and request types from the same Pydantic contracts."""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'backend'))
from app.main import app  # noqa: E402
from app import schemas  # noqa: E402
from app import statement_store, statement_api  # noqa: E402
from app import policy_contract, policy_api, policy_responses, policy_context_contract  # noqa: E402
from app.ocr_contract import OcrReviewInput, OcrBatchReviewInput, OcrRecordInput  # noqa: E402
from app.reference_contract import (  # noqa: E402
    ReferenceSearchInput, ReferenceChoiceInput, ReferenceRequirement, ReferenceSupportInput,
)


def ts_type(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts_type(part) for part in schema['anyOf'])
    kind = schema.get('type')
    if kind == 'array':
        return f'Array<{ts_type(schema.get("items", {}))}>'
    if kind == 'object':
        if 'properties' in schema:
            required = schema.get('required', [])
            return '{ ' + '; '.join(f'{json.dumps(key)}{"" if key in required else "?"}: {ts_type(value)}'
                                   for key, value in schema['properties'].items()) + ' }'
        additional = schema.get('additionalProperties')
        return f'Record<string, {ts_type(additional) if isinstance(additional, dict) else "unknown"}>'
    return {'string': 'string', 'number': 'number', 'integer': 'number', 'boolean': 'boolean', 'null': 'null'}.get(kind, 'unknown')


def artifacts():
    names = ['BookInput', 'LedgerInput', 'SnapshotInput', 'CheckInput', 'InvestigateInput', 'SimulationInput', 'ReviewInput']
    content = '// Generated by scripts/generate_contracts.py. Edit the backend Pydantic contracts instead.\n'
    content += '// Money is a decimal string. Runtime validation remains authoritative.\n\n'
    for name in names:
        content += f'export type {name} = {ts_type(getattr(schemas, name).model_json_schema())}\n'
    content += f'export type OcrReviewInput = {ts_type(OcrReviewInput.model_json_schema())}\n'
    content += f'export type OcrRecordInput = {ts_type(OcrRecordInput.model_json_schema())}\n'
    content += f'export type OcrBatchReviewInput = {ts_type(OcrBatchReviewInput.model_json_schema())}\n'
    for cls in (ReferenceSearchInput, ReferenceChoiceInput, ReferenceRequirement, ReferenceSupportInput):
        content += f'export type {cls.__name__} = {ts_type(cls.model_json_schema())}\n'
    statement_names = ('TextLine', 'SourceLine', 'LabelFragment', 'StatementContext', 'ColumnHeader',
                       'StatementObservation', 'BalanceObservation', 'StatementReport', 'StatementDataset')
    for name in statement_names:
        content += f'export type {name} = {ts_type(getattr(statement_store, name).model_json_schema())}\n'
    for name in ('StatementDatasetList', 'StatementReportsPage', 'StatementSourceIdentity',
                 'StatementPageGeometry', 'StatementEvidenceDetail'):
        content += f'export type {name} = {ts_type(getattr(statement_api, name).model_json_schema())}\n'
    for name in ('ConfirmedCondition', 'PolicyObservation'):
        content += f'export type {name} = {ts_type(getattr(policy_contract, name).model_json_schema())}\n'
    content += f'export type PolicyObservationInput = {ts_type(policy_api.PolicyObservationInput.model_json_schema())}\n'
    for name in ('PolicyPackIdentity', 'PolicySource', 'PolicyResult', 'PolicyRule', 'PolicyCatalogResponse',
                 'PolicyObservationResponse', 'PolicyEvidenceLocator', 'PolicyAnnotationEnvelope',
                 'PolicyCheckBinding', 'PolicyCheckResponse'):
        content += f'export type {name} = {ts_type(getattr(policy_responses, name).model_json_schema())}\n'
    for name in ('CapturedPolicyCheck', 'CapturedPolicyObservation', 'InvestigationPolicyContextPayload', 'InvestigationPolicyContextResponse'):
        content += f'export type {name} = {ts_type(getattr(policy_context_contract, name).model_json_schema())}\n'
    return {ROOT / 'docs/openapi.json': json.dumps(app.openapi(), ensure_ascii=False, indent=2) + '\n',
            ROOT / 'frontend/src/generated/contracts.ts': content}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='Fail if checked-in contracts differ from backend')
    args = parser.parse_args()
    changed = []
    for path, content in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                changed.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    if changed:
        raise SystemExit('Contract drift: ' + ', '.join(changed))
    print('API and request contracts are consistent.' if args.check else 'API and request contracts generated.')


if __name__ == '__main__':
    main()
