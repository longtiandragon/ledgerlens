function syntheticPdf(){
 const stream=(text:string)=>`BT /F1 18 Tf 50 740 Td (${text}) Tj ET`
 const objects=['<< /Type /Catalog /Pages 2 0 R >>','<< /Type /Pages /Kids [4 0 R 6 0 R] /Count 2 >>','<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>']
 for(const [index,text] of ['LedgerLens synthetic page one','Page two 100000.00'].entries()){
  objects.push(`<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R >> >> /Contents ${5+index*2} 0 R >>`)
  const data=stream(text);objects.push(`<< /Length ${Buffer.byteLength(data)} >>\nstream\n${data}\nendstream`)
 }
 let pdf='%PDF-1.4\n';const offsets=[0]
 for(const [index,obj] of objects.entries()){offsets.push(Buffer.byteLength(pdf));pdf+=`${index+1} 0 obj\n${obj}\nendobj\n`}
 const xref=Buffer.byteLength(pdf);pdf+=`xref\n0 ${objects.length+1}\n0000000000 65535 f \n`+offsets.slice(1).map(offset=>`${String(offset).padStart(10,'0')} 00000 n \n`).join('')
 pdf+=`trailer\n<< /Size ${objects.length+1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`
 return Buffer.from(pdf)
}

