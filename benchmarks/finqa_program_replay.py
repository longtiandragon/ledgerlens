"""Replay official dev reference programs against external execution answers.

This is arithmetic-component verification with supplied gold programs, NOT a
question-answering or model reasoning benchmark. Answers/programs stay entirely
in this evaluator; runtime calculator receives only a program and source table.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import Counter
from datetime import UTC, datetime
from decimal import Decimal, InvalidOperation, ROUND_HALF_EVEN, localcontext
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'backend'))

from app.financial_math import VERSION, NumericProgramError, execute_numeric_program  # noqa: E402
from datasets.finqa import load_observed, read_json, verify  # noqa: E402


def compare_external_answer(actual: dict, expected: object) -> dict:
    if isinstance(expected, str) and expected in {'yes', 'no'}:
        return {'exact_at_5_decimal_places': actual['value_kind'] == 'comparison' and actual['value'] == expected,
                'within_half_last_decimal': actual['value_kind'] == 'comparison' and actual['value'] == expected}
    if type(expected) is bool or not isinstance(expected, (str, int, Decimal)):
        raise ValueError('Invalid external answer')
    try:
        expected_value = Decimal(str(expected))
        if not expected_value.is_finite():
            raise ValueError('Nonfinite external answer')
        if actual['value_kind'] != 'decimal':
            return {'exact_at_5_decimal_places': False, 'within_half_last_decimal': False}
        with localcontext() as context:
            context.prec = 120
            value = Decimal(actual['value'])
            rounded = value.quantize(Decimal('0.00001'), rounding=ROUND_HALF_EVEN)
            return {'exact_at_5_decimal_places': rounded == expected_value,
                    'within_half_last_decimal': abs(value - expected_value) <= Decimal('0.000005')}
    except InvalidOperation:
        raise ValueError('Invalid external answer') from None


def replay_case(observed: dict, evaluator: dict) -> dict:
    if observed['id'] != evaluator['id']:
        raise ValueError('Observed and evaluator identity mismatch')
    program = evaluator['qa']['program']
    row = {'id': observed['id'], 'program_sha256': hashlib.sha256(program.encode()).hexdigest()}
    try:
        actual = execute_numeric_program(program, observed['table'])
        row.update(status='executed', **compare_external_answer(actual, evaluator['qa']['exe_ans']),
                   operations=[step['operation'] for step in actual['steps']])
    except NumericProgramError as error:
        row.update(status='unsupported_or_failed', error={'code': error.code, 'step': error.step},
                   exact_at_5_decimal_places=False, within_half_last_decimal=False)
    return row


def run_replay(dataset: Path) -> dict:
    validation = verify(dataset)
    observed = load_observed(dataset / 'observed/dev.json')
    evaluator = read_json((dataset / 'evaluator/dev.json').read_bytes())
    answers = {row['id']: row for row in evaluator['records']}
    if set(answers) != {row['id'] for row in observed['records']}:
        raise ValueError('Evaluator coverage mismatch')
    rows = [replay_case(row, answers[row['id']]) for row in observed['records']]
    executed = sum(row['status'] == 'executed' for row in rows)
    exact = sum(row['exact_at_5_decimal_places'] for row in rows)
    tolerance = sum(row['within_half_last_decimal'] for row in rows)
    return {'schema_version': 'finqa-reference-program-replay-v1', 'created_at': datetime.now(UTC).isoformat(),
            'calculator_version': VERSION, 'source_sha256': observed['source_sha256'], 'source_verification': validation,
            'metric_scope': 'arithmetic_execution_of_supplied_official_dev_programs_not_model_QA',
            'reference_semantics_url': 'https://github.com/czyssrs/FinQA/blob/main/code/evaluate/evaluate.py',
            'records': len(rows), 'executed': executed, 'unsupported_or_failed': len(rows) - executed,
            'exact_matches_at_5_decimal_places': exact, 'within_half_last_decimal': tolerance,
            'unmatched_executed': executed - exact,
            'errors': dict(Counter(row['error']['code'] for row in rows if 'error' in row)),
            'operation_counts': dict(Counter(op for row in rows for op in row.get('operations', []))),
            'model_requests': 0, 'numeric_model_accuracy': None, 'accounting_accuracy': None,
            'limitations': ['Gold program is supplied by the evaluator; this does not test question understanding or extraction.',
                            'Official dev is not a sealed test set; external answers are never generated by our calculator.',
                            'Decimal precision 50 and explicit half-even rounding differ from upstream binary-float arithmetic.',
                            'Table row ambiguity and unknown cell formats are rejected rather than guessed or replaced with zero.',
                            'Arithmetic verification does not verify source grounding, units, business meaning or accounting policy.'],
            'cases': rows}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dataset', type=Path, default=Path('.local/finqa'))
    parser.add_argument('--report', type=Path, default=Path('.local/reports/finqa-program-replay-v1.json'))
    parser.add_argument('--summary', type=Path, default=Path('docs/finqa-program-replay-summary.json'))
    args = parser.parse_args()
    if args.report.exists() or args.summary.exists():
        parser.error('Refusing to overwrite an existing validation result')
    result = run_replay(args.dataset)
    for path, value in [(args.report, result), (args.summary, {k: v for k, v in result.items() if k != 'cases'})]:
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open('x', encoding='utf-8') as handle:
            json.dump(value, handle, ensure_ascii=False, indent=2, allow_nan=False)
            handle.write('\n')
    print(json.dumps({k: result[k] for k in ('records', 'executed', 'exact_matches_at_5_decimal_places',
                                            'unmatched_executed', 'errors', 'model_requests')}, ensure_ascii=False))
    return 0 if result['executed'] == result['records'] and result['unmatched_executed'] == 0 else 1


if __name__ == '__main__':
    raise SystemExit(main())
