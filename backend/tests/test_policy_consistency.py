def test_evaluation_needs_no_runtime_file_reads(monkeypatch):
    # Loaded normative code may compute its own identity at import. Executing a
    # policy check must not open the evaluator answer bank or any other file.
    observation, context = inputs('resale_inventory', treatment='inventory')

    def forbidden(*args, **kwargs):
        raise AssertionError('Runtime policy evaluation attempted filesystem access')

    with monkeypatch.context() as scoped:
        scoped.setattr(builtins, 'open', forbidden)
        scoped.setattr(Path, 'open', forbidden)
        scoped.setattr(Path, 'read_text', forbidden)
        scoped.setattr(Path, 'read_bytes', forbidden)
        result = evaluate_policy(observation, context)
    assert_outcome(result, status='normal', treatment='inventory', rule='POLICY_CAS_RESALE_INVENTORY')


