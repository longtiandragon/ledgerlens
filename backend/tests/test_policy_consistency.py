def parse(model, value):
    return model.model_validate_json(json.dumps(value, ensure_ascii=False))


def inputs(topic, *, framework='CAS', treatment='unknown', values=None, confirmations=None,
           beneficiary='unknown', beneficiary_confirmation='human_confirmed', period='2026-10',
           as_of='2026-10-02T08:00:00+00:00', known_at='2026-10-01T08:00:00+00:00'):
    values = deepcopy(REQUIRED_YES[topic]) if values is None else deepcopy(values)
    confirmations = confirmations or {}
    conditions = {name: {'value': value, 'confirmation': confirmations.get(name, 'human_confirmed'),
                         'evidence_ids': ['ev-' + name]} for name, value in values.items()}
    observation = {'observation_id': 'obs-A', 'book_id': 'book-A', 'snapshot_id': 'snapshot-A', 'topic': topic,
                   'conditions': conditions, 'reported_treatment': treatment,
                   'treatment_evidence_ids': ['ev-treatment'] if treatment != 'unknown' else [],
                   'beneficiary': beneficiary, 'beneficiary_confirmation': beneficiary_confirmation,
                   'beneficiary_evidence_ids': ['ev-beneficiary'] if beneficiary != 'unknown' else []}
    references = [item for condition in conditions.values() for item in condition['evidence_ids']]
    references += observation['treatment_evidence_ids'] + observation['beneficiary_evidence_ids']
    context = {'book_id': 'book-A', 'snapshot_id': 'snapshot-A', 'framework': framework, 'period': period,
               'as_of': as_of, 'evidence': [{'evidence_id': item, 'book_id': 'book-A',
               'snapshot_id': 'snapshot-A', 'known_at': known_at} for item in references]}
    return parse(PolicyObservation, observation), parse(PolicyCheckContext, context)


def assert_outcome(result, *, status, treatment, rule):
    assert result['status'] == status
    assert result['expected_treatment'] == treatment
    assert result['rule_id'] == rule
    assert result['source'] == PINNED_SOURCES[rule]
    assert result['policy_rule_identity'] == policy_rule_identity()
    assert result['reason']
    assert result['scope_note']


